// nameSuffixes — типовые слова, которые в русских названиях админединиц стоят
// в КОНЦЕ («Клинский район», «Краснодарский край», «Одинцовский городской
// округ»). Отдельный список, а не namePrefixes задом наперёд: в начале и в
// конце встречаются разные слова. «Район» бывает только суффиксом («район
// Тверской» никто не пишет), а «муниципальный округ» — и тем, и другим.
//
// В подпись такое слово не превращаем: «Клинский» без «района» — не название,
// а обрубок прилагательного, и как склеивать обратно, правило не знает. Поэтому
// суффикс только помечает единицу как пробел — решает человек, глядя на сводку.
var nameSuffixes = []string{
	"муниципальный округ",
	"городской округ",
	"муниципальный район",
	"городское поселение",
	"сельское поселение",
	"автономный округ",
	"автономная область",
	"республика",
	"поселение",
	"область",
	"район",
	"округ",
	"улус",
	"край",
}

func init() {
	// Длинные вперёд: иначе «посёлок» съел бы «посёлок городского типа», а
	// «округ» — «городской округ».
	byLenDesc := func(ss []string) {
		sort.SliceStable(ss, func(i, j int) bool { return len(ss[i]) > len(ss[j]) })
	}
	byLenDesc(namePrefixes)
	byLenDesc(nameSuffixes)
}

// unitGap — единица, которую словарь не распознал, ХОТЯ похоже, что мог бы:
// строка рабочего списка, а не всякий откат на подпись слота. Разница
// принципиальная: у «Москвы» и «Тверского» типового слова нет нигде, подпись
// слота там верна, и чинить нечего — попади они в список, он бы состоял из них
// одних, а чистка их не убирала бы (вернулись бы на следующем locate).
//
// Записываем два случая, каждый лечится правкой в этом файле:
//
//   - `place=*` с типом не из placeLabels — дыра в словаре типов;
//   - админединица, у которой типовое слово стоит в КОНЦЕ имени («Клинский
//     район», «Одинцовский городской округ») — дыра в правиле: мы ищем тип
//     только в начале.
//
// Ложные срабатывания возможны (граница с именем «Красное Село» кончается на
// «село», хотя это часть названия) — список рабочий, его читает человек.
//
// Чего список НЕ покажет: единицу, у которой тег знаком, а типовое слово сидит в
// начале имени. «Коттеджный посёлок «2x2»» — это place/neighbourhood, словарь
// типов его знает и отдаёт «Квартал», отката на слот не происходит, и пробел
// молчит. Такие находятся только глазами; так нашлась и эта пара слов.
type unitGap struct {
	Class, Type string
	AdminLevel  int
	Name        string
}

// nameQuotes — кавычки, которыми в OSM обрамляют собственное имя после типа.
// Все формы сразу: русские «ёлочки», прямые и типографские.
const nameQuotes = `«»"'„“”`

// unitTitle — подпись и имя единицы для UI. slotLabel — запасной вариант,
// подпись слота («Город»), она же результат, когда тип распознать не удалось.
// Третье значение непусто, когда откат похож на пробел словаря, — такие
// единицы копятся в таблице unmapped_unit и печатаются в недельной сводке.
func unitTitle(e *nomAddressEntry, slotLabel string) (label, name string, gap *unitGap) {
	if e == nil {
		return slotLabel, "", nil
	}
	name = strings.TrimSpace(e.LocalName)
	// Имя главнее тега: если единица сама себя называет («муниципальный округ
	// Истра»), это самое точное, что о ней известно, и заодно убирает повтор в
	// шапке, где имя стоит строкой выше подписи.
	if pref, rest, ok := cutNamePrefix(name); ok {
		return capitalizeFirst(pref), rest, nil
	}
	if e.Class == "place" {
		if l, ok := placeLabels[e.Type]; ok {
			return l, name, nil
		}
		return slotLabel, name, &unitGap{Class: e.Class, Type: e.Type, AdminLevel: e.AdminLevel, Name: name}
	}
	if typeSuffix(name, slotLabel) {
		return slotLabel, name, &unitGap{Class: e.Class, Type: e.Type, AdminLevel: e.AdminLevel, Name: name}
	}
	return slotLabel, name, nil
}

// typeSuffix — имя кончается типовым словом, И это слово не то, которым мы
// собираемся подписать канал. Вторая половина условия убирает главный источник
// шума: «Московская область» в слоте Области кончается на «область», но подпись
// там и так «Область» — чинить нечего. А «Краснодарский край» с той же подписью
// — уже пробел: слово в данных есть, и оно другое.
func typeSuffix(name, slotLabel string) bool {
	lower := strings.ToLower(name)
	for _, p := range nameSuffixes {
		if !strings.HasSuffix(lower, " "+p) {
			continue
		}
		return !strings.EqualFold(p, slotLabel)
	}
	return false
}

// unitDictHash — отпечаток обоих словарей. Им помечается каждая строка
// unmapped_unit: правка словаря меняет отпечаток, и при старте сервер выносит
// строки, снятые прежним словарём (см. Store.DeleteUnmappedUnitsExcept). Так
// «после обновления словаря чистим базу» происходит само, а в списке остаётся
// только то, чего новый словарь всё ещё не знает.
var unitDictHash = sync.OnceValue(func() string {
	keys := make([]string, 0, len(placeLabels))
	for k, v := range placeLabels {
		keys = append(keys, k+"="+v)
	}
	sort.Strings(keys) // map-итерация недетерминирована, а отпечаток обязан быть стабилен
	h := sha256.Sum256([]byte(strings.Join(keys, ",") + "|" +
		strings.Join(namePrefixes, ",") + "|" + strings.Join(nameSuffixes, ",")))
	return hex.EncodeToString(h[:])[:8]
})

// cutNamePrefix отрезает типовое слово в начале имени: «муниципальный округ
// Истра» → «муниципальный округ» + «Истра». Требуется пробел после слова и
// непустой остаток: «Красное Село» — имя целиком, а не тип с остатком.
//
// У остатка снимаем кавычки: в OSM собственное имя после типа часто закавычено
// («СНТ «Марушкино-92»», «Огородническое товарищество "Дружба"»), и без этого в
// шапке остались бы висячие кавычки от разрезанной пары.
func cutNamePrefix(name string) (prefix, rest string, ok bool) {
	lower := strings.ToLower(name)
	for _, p := range namePrefixes {
		if !strings.HasPrefix(lower, p+" ") {
			continue
		}
		rest = strings.Trim(strings.TrimSpace(name[len(p):]), nameQuotes)
		rest = strings.TrimSpace(rest)
		if rest == "" {
			continue
		}
		return name[:len(p)], rest, true
	}
	return "", name, false
}

func capitalizeFirst(s string) string {
	r := []rune(s)
	if len(r) == 0 {
		return s
	}
	r[0] = unicode.ToUpper(r[0])
	return string(r)
}
