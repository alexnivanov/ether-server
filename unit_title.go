// Подпись канала — про то, ЧЕМ единица является, а не в какой слот попала.
//
// Слот (`level`) и подпись (`label`) отвечают на разные вопросы. Слот — про
// охват: он держит структуру набора, иконку, порядок в списке и полосу лимита,
// и потому обязан быть из фиксированного набора. Подпись — про сам объект, и
// вот её фиксированный набор врёт: под Истрой в слот «Город» ложится
// муниципальный округ, а в слот «Район» — деревня Карцево. Структура при этом
// верная (округ действительно шире деревни), а звания — нет.
//
// Оба слова берём из данных OSM, а не придумываем:
//
//   - у `place/*` тип стоит прямо в теге (`place=hamlet` → «Деревня»);
//   - у `boundary/administrative` типа нет, но он почти всегда в самом имени
//     («муниципальный округ Истра», «Республика Татарстан») — тогда типовое
//     слово переезжает из имени в подпись, и в шапке нет повтора.
//
// Сверено с `official_status` (русское OSM-сообщество проставляет его тегом):
// у Карцева `ru:деревня`, у Истры `ru:муниципальный округ` — оба правила дают
// ровно эти слова. Читать сам `official_status` нельзя: в цепочке `/details`
// его нет, extratags Nominatim отдаёт только для объекта, о котором спросили, —
// это +1 запрос на каждую единицу набора. На публичном сервере с лимитом
// 1 req/s такой геокодинг вырос бы с ~2 до ~7 секунд. Со своим инстансом (28 мс
// на запрос) цена исчезает, и тогда точное слово можно брать из данных.
//
// Не распозналось — остаётся подпись слота, как было: правило только добавляет
// точности там, где она есть, и нигде не делает хуже.

// placeLabels — тип `place=*` (интернациональный тег OSM) в русское слово.
// Неполнота намеренна: чего здесь нет, то падает на подпись слота. Village →
// «Село», хотя в OSM им метят и посёлки: точнее различает только
// official_status, а ошибка стоит одного слова в шапке.
var placeLabels = map[string]string{
	// Страна приходит в цепочке как place/country, и без неё в словаре список
	// пробелов возглавляла `place/country «Россия»` — 24 строки в первой же
	// сводке (05–12.09). Слот по имени совпадает, но узнаём мы это из типа, а не
	// из того, в какой слот единица легла: фильтровать пробелы по слоту нельзя —
	// у Области подпись врёт на «Краснодарском крае», и этот сигнал нужен.
	"country":       "Страна",
	"city":          "Город",
	"town":          "Город",
	"village":       "Село",
	"hamlet":        "Деревня",
	"borough":       "Округ",
	"suburb":        "Район",
	"quarter":       "Квартал",
	"neighbourhood": "Квартал",
	// Садовые участки: в РФ это СНТ и огороднические товарищества, и живут там
	// подолгу — канал осмысленный, подписи не было. Нашлось сводкой за 05–12.09.
	"allotments": "Садовое товарищество",
}

// namePrefixes — типовые слова, с которых начинается имя админединицы в РФ
